def face(eyes, mouth, extra=None):
    g = [list('.' * 16) for _ in range(16)]
    import math
    for y in range(16):
        for x in range(16):
            if (x - 7.5) ** 2 + (y - 7.5) ** 2 <= 7.4 ** 2: g[y][x] = 'Y'
            if (x - 7.5) ** 2 + (y - 7.5) ** 2 <= 7.4 ** 2 and (x - 7.5) ** 2 + (y - 7.5) ** 2 > 6.3 ** 2 and (y > 9 or x > 11): g[y][x] = 'O'
    for (x, y) in [(4, 3), (5, 3), (3, 4), (4, 4), (3, 5)]: g[y][x] = 'y'
    for (x, y, c) in eyes + mouth + (extra or []): g[y][x] = c
    return '\n' + '\n'.join(''.join(r) for r in g)
